;----------------------------------------------------------------------------
; MXOS
; ROM.COM - драйвер внешнего ROM-диска H: через второй ВВ55
; Адаптация оригинального DISK-H.COM; одна 64-КБ страница, только чтение.
;
; Номер функции передаётся в регистре b:
;   b == 1 - отказ записи: CF=1, diskWriteErr=1;
;   b == 2 - прочитать сектор: de=0000h..00FFh, hl=буфер 256 байт, CF=0;
;   b == 3 - размер в de, адрес DISK_INFO в hl, bc=0 (линейное выделение);
;   b == 0FFh - адрес имени и описания в hl (две строки с нулём), CF=0.
;
; Остальные функции, включая B=4 и B=5, возвращают CF=1.
;
; Порт A - данные, B - A0-A7, C - A8-A15. PC6 клавиатурного ВВ55
; разрешает ROM уровнем 1. После чтения PC6 сбрасывается, а порты второго
; ВВ55 возвращаются в режим ввода. Старший байт номера сектора игнорируется;
; переключения банков и проверки диапазона здесь нет.
;
; Это протокол внешнего 64-КБ ROM, а не AT29-плата и не системный маппер
; FFFEh. Большой системный ROM читает встроенный драйвер DOS; запись на
; системную flash обслуживает FlashSys, на внешнюю - Flash или FlashFst.
;
; 2022-02-15 Разработано SpaceEngineer
;----------------------------------------------------------------------------

    INCLUDE "../include/mxos.inc"

; Унаследованные команды и маски flash-платы; в ROM-протоколе не используются.
LATCH_0 = 0Ah   ; пин защёлки ИР22 = 0
LATCH_1 = 0Bh   ; пин защёлки ИР22 = 1
WRITE_0 = 0Ch   ; пин записи = 0
WRITE_1 = 0Dh   ; пин записи = 1
READ_0  = 0Eh   ; пин чтения = 0
READ_1  = 0Fh   ; пин чтения = 1

; Маски управляющих сигналов flash-платы
MASK_STADBY = 0C0h  ; пин защёлки ИР22 = 0, пин записи = 1, пин чтения = 1
MASK_READ   = 040h  ; пин защёлки ИР22 = 0, пин записи = 1, пин чтения = 0

; Накопитель, куда назначается драйвер
DRIVE       = 7     ; "H"

; Ёмкость до распознавания BPB: 64 КБ / 256 байт
DISK_SECTORS = 64 * 4

; Схема внешнего ROM-диска:
; Порт A - данные (ввод)
; Порт B - адрес [A0-A7]  (вывод)
; Порт C - адрес [A8-A15] (вывод)
; Вывод С6 порта клавиатуры (пин 11) - включение ПЗУ (лог. 1)

;----------------------------------------------------------------------------

    ORG     0DE00h

    ; Регистрируем физический драйвер H: в DOS.
    ld      a, DRIVE
    ld      hl, Driver
    call    bios_installDriver

    ; Установщик возвращает общий DISK_INFO выбранного диска.
    ld      (v_diskInfo), hl
    ret

Driver:
    ; B=1/2 сохраняют BC/DE/HL, AF и флаги разрушаются.
    ; Для B=3 и B=0FFh регистровый контракт приведён у обработчиков.
    ld      a, b
    cp      0FFh
    jp z,   FuncInfo
    cp      1
    jp nz,  DriverNotWrite
    ld      (bios_vars.diskWriteErr), a
    scf
    ret                 ; запись - не поддерживается
DriverNotWrite:
    cp      2
    jp z,   FuncRead    ; чтение
    cp      3
    jp z,   FuncSize    ; размер
    scf                 ; неизвестная функция, включая запись B=5
    ret                 ; иначе выход

;----------------------------------------------------------------------------
; Функция 3 - определение объёма накопителя.
;
; Выход:
;   de = число секторов из распознанного BPB, иначе DISK_SECTORS;
;   hl = адрес DISK_INFO;
;   bc = 0, подсказка линейного выделения.
;
; Разрушает:
;   af и флаги; CF не является результатом этой функции.

FuncSize:
    ; Проверяем, загружена ли геометрия тома.
    ld      hl, (v_diskInfo)            ; hl = адрес структуры
    ld      de, DISK_INFO.isValid       ; de = смещение поля
    add     hl, de                      ; hl = адрес поля
    ld      a, (hl)                     ; a = isValid

    ; До распознавания тома сообщаем физическую ёмкость.
    ld      de, DISK_SECTORS
    cp      DISK_VALID
    jp nz,  fsExit

    ; Для распознанного тома берём totalSectors из DISK_INFO.
    ld      hl, (v_diskInfo)            ; hl = адрес структуры
    ld      de, DISK_INFO.totalSectors  ; de = смещение поля
    add     hl, de                      ; hl = адрес поля
    ld      e, (hl)
    inc     hl
    ld      d, (hl)

fsExit:
    ld      bc, 0
    ; Возвращаем в hl адрес структуры DISK_INFO
    ld      hl, (v_diskInfo)
    ret

;----------------------------------------------------------------------------
; Функция 2 - чтение сектора из внешнего ROM.
;
; Вход:
;   de = номер 256-байтного сектора, 0000h..00FFh;
;   hl = адрес буфера в основном ОЗУ.
;
; Выход:
;   буфер заполнен; при вызове через Driver CF=0.
;
; Сохраняет:
;   bc, de, hl.
;
; Разрушает:
;   af и флаги, кроме CF (сохраняется из диспетчера).

FuncRead:
    ; Сохранение регистров
    push    hl
    push    de
    push    bc

    ; Настройка портов ВВ55
    ld      a, 90h              ; порт A - ввод, порты B и C - вывод 
    ld      (IO_PROG_MODE), a
    ld      a, 0Dh              ; вывод С6 порта клавиатуры = 1
    ld      (IO_KEYB_MODE), a

    ; В 64-КБ ROM адрес сектора равен E << 8; исходный D не используется.
    ld      d, e
    ld      e, 0

; Горячий цикл: 14 байт, 66 тактов/байт, 8,448 мс на сектор при 2 МГц.
; Обычный и худший путь совпадают. На байт: две записи адреса в ВВ55,
; одно чтение данных ВВ55 и одна запись в ОЗУ.
ReadLoop:
    ex      de, hl          ; hl = адрес в ПЗУ, de = адрес в памяти
    ld      (IO_PROG_B), hl ; порт B = младший байт адреса, порт C = старший байт адреса
    ld      a, (IO_PROG_A)  ; a = байт из ПЗУ
    ex      de, hl          ; hl = адрес в памяти, de = адрес в ПЗУ
    ld      (hl), a         ; сохраняем байт в память
    inc     hl              ; следующий адрес в памяти
    inc     e               ; следующий адрес в ПЗУ
    jp nz,  ReadLoop        ; повтор цикла, пока адрес в ПЗУ не пересечет XX00h

    ; Восстановление портов, регистров и выход
    push    af
    ld      a, 0Ch          ; вывод С6 порта клавиатуры = 0
    ld      (IO_KEYB_MODE), a
    ld      a, 9Bh          ; Порты A, B, C - ввод
    ld      (IO_PROG_MODE), a
    pop     af
    pop     bc
    pop     de
    pop     hl
    ret

;----------------------------------------------------------------------------
; Чтение байта ROM; вспомогательная точка, секторный цикл её не вызывает.
;
; Вход:
;   de = адрес в 64-КБ ROM;
;   ВВ55 уже настроен на чтение, PC6 клавиатурного ВВ55 установлен.
;
; Выход:
;   a = байт ROM; разрешение ROM и направления портов не меняются.
;
; Сохраняет:
;   bc, de, hl и флаги.

ReadByteFromChip:
    ex      de, hl
    ld      (IO_PROG_B), hl
    ld      a, (IO_PROG_A)
    ex      de, hl
    ret

;----------------------------------------------------------------------------
; Функция 0FFh - дескриптор физического драйвера для инфо-панели NC.
;
; Выход:
;   hl = адрес имени и описания (две ASCII-строки с нулём), CF=0;
;   b = DISK_TECH_ROM, c = DISK_CAP_READ.
;
; Сохраняет:
;   de.
;
; Разрушает:
;   af и флаги.
FuncInfo:
    ld      bc, DISK_TECH_ROM * 256 + DISK_CAP_READ
    ld      hl, DriverInfo
    or      a
    ret
DriverInfo:     DB "ROM",0,"64K read only",0

;----------------------------------------------------------------------------
; Адрес DISK_INFO, полученный при регистрации драйвера.

v_diskInfo:     DW 0

;----------------------------------------------------------------------------

    ; Проверка - ROM.COM не должен вылезать за эти пределы
    ASSERT_DONT_FIT 0E000h

    END
