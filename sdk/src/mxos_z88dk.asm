; Пять 16-битных слов: entry, AF, BC, DE, HL; единственный аргумент в HL.
; Мост нереентерабелен: меняется только операнд CALL, пакет хранит вызывающий.
    SECTION code_clib
    INCLUDE "mxos_syscall_ids.inc"
    PUBLIC _mxos_bios_call
    PUBLIC _mxos_call_packet
    PUBLIC _mxos_pit_read, _mxos_pit_get_port
    defc _mxos_pit_read = io_pitRead
    PUBLIC _mxos_queue_bind, _mxos_queue_flush
    PUBLIC _mxos_memmove_far, _mxos_puts_local
    PUBLIC _mxos_printString_bank, _mxos_printString_main
    PUBLIC _mxos_printStringLim
    PUBLIC _mxos_memcpy_far
    PUBLIC _mxos_memtop, _mxos_set_memtop
    PUBLIC _mxos_getch, _mxos_getkey, _mxos_keyscan, _mxos_putch, _mxos_puts
    PUBLIC _mxos_cls, _mxos_cursor_get, _mxos_cursor_set, _mxos_upper

; Консоль/таймер используют общий ABI и одинаково работают в main и BANK.

;----------------------------------------------------------------------------
; MXOS
; Получить базу каналов таймера и пространство адресации платформы.
; вход:
;   HL = адрес выходного слова в текущей странице.
; выход:
;   По переданному адресу записана база. HL = 0 для MMIO, 1 для IN/OUT.
;   AF и DE разрушены.
;----------------------------------------------------------------------------
_mxos_pit_get_port:
    push hl
    call io_pitGetPort
    ex de,hl
    pop hl
    ld (hl),e
    inc hl
    ld (hl),d
    ld hl,0
    ret nc
    inc l
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Выполнить системный запрос через пакет MXOS_CALL_PACKET.
;
; вход:
;   hl = адрес пакета в странице вызывающего. Первое слово задаёт номер службы, далее
;   лежат её параметры.
;
; выход:
;   hl = результат AF диспетчера (h = a, l = флаги, бит 0 = CF). Служба записывает
;   результаты в пакет согласно своему ABI.
;----------------------------------------------------------------------------

_mxos_call_packet:
    ld c,(hl)
    inc hl
    ld b,(hl)
    inc hl
    ex de,hl
    call mx_callPacket
    push af
    pop hl
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Перенести диапазон между страницами службой MEM_OP_MOVE.
;
; вход:
;   hl = адрес заполненного MXOS_FAR_COPY в странице вызывающего.
;
; выход:
;   h = байт результата a, бит 0 в l = CF службы MEM. При успехе назначение содержит
;   перенесённые байты. Допустимо перекрытие внутри любой страницы, включая DATA.
;----------------------------------------------------------------------------

_mxos_memmove_far:
    xor a
    call mx_memory
    push af
    pop hl
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Вывести строку из страницы вызывающей программы через общий вход локальной печати.
;
; вход:
;   hl = адрес строки, заканчивающейся нулём, в текущей странице.
;
; выход:
;   Тот же вход и результат, что у _mxos_puts_local. Возвращаемого значения для C нет.
;----------------------------------------------------------------------------

_mxos_printString_bank:

;----------------------------------------------------------------------------
; MXOS
;
; Вывести строку через операцию печати MEM.
;
; вход:
;   hl = локальный адрес строки с завершающим нулём.
;
; выход:
;   Строка передана на вывод. С точки зрения sccz80 функция возвращает void.
;----------------------------------------------------------------------------

_mxos_puts_local:
    ld a,5
    jp mx_memory
;----------------------------------------------------------------------------
; MXOS
;
; Напечатать строку из основной памяти.
;
; вход:
;   hl = адрес строки с завершающим нулём в MAIN, в том числе при вызове из банка.
;
; выход:
;   BIOS выводит символы строки, результат функции C — void.
;----------------------------------------------------------------------------

_mxos_printString_main:
    call mx_callRegs
    defw MXOS_BIOS_PRINT_STRING_MAIN
    ret

;----------------------------------------------------------------------------
; MXOS
; Печать точного диапазона в странице вызывающего с обработкой управляющих кодов.
; вход: стек sccz80 — адрес возврата, число байтов, указатель на текст.
; выход: HL указывает за последним байтом. Аргументы снимает вызывающий.
;----------------------------------------------------------------------------
_mxos_printStringLim:
    pop de
    pop bc
    pop hl
    push hl
    push bc
    push de
    call mx_callRegs
    defw MXOS_BIOS_PRINT_STRING_LIM
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Скопировать данные по двум FAR-адресам через прямой вход MEM.
;
; вход:
;   hl = адрес MXOS_FAR_COPY с исходной и целевой страницами, адресами и длиной в
;   байтах.
;
; выход:
;   hl = AF службы копирования. Бит 0 регистра l установлен при отказе, h содержит a.
;----------------------------------------------------------------------------

_mxos_memcpy_far:
    call mx_memcpyFar
    push af
    pop hl
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Вывести один символ через BIOS.
;
; вход:
;   l = код символа.
;
; выход:
;   Символ передан PRINT_CHAR через c. Возвращаемого значения для C нет.
;----------------------------------------------------------------------------

_mxos_putch:
    ld c,l
    jp mx_printChar

;----------------------------------------------------------------------------
; MXOS
;
; Вывести строку через банковый вызов BIOS.
;
; вход:
;   hl = локальный адрес строки до нулевого байта.
;
; выход:
;   BIOS выводит строку от имени текущей страницы. Возвращаемого значения для C нет.
;----------------------------------------------------------------------------

_mxos_puts:
    call mx_callRegs
    defw MXOS_BIOS_PRINT_STRING_BANK
    ret
; IO.SYS direct DOS/EXEC ABI. Preserve a valid key code 00h in the result.
    PUBLIC _mxos_bank_key_poll, _mxos_bank_getch
    PUBLIC _mxos_bank_getch_cursor
    PUBLIC _mxos_bank_key_modifiers, _mxos_bank_key_shift

;----------------------------------------------------------------------------
; MXOS
;
; Прочитать состояние модификаторов штатной банковой клавиатуры.
;
; вход:
;   Параметров нет. В странице программы установлен клавиатурный сегмент IO.SYS.
;
; выход:
;   hl = маска: бит 0 — Shift, бит 1 — Ctrl. Старший байт равен нулю.
;----------------------------------------------------------------------------

_mxos_bank_key_modifiers:
    call io_bankKeyModifiers
    ld l,a
    ld h,0
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Прочитать линию Shift через локальный вход IO.SYS.
;
; вход:
;   Параметров нет. Доступен клавиатурный сегмент IO.SYS.
;
; выход:
;   hl = 1 при нажатом Shift, иначе 0.
;----------------------------------------------------------------------------

_mxos_bank_key_shift:
    call io_bankKeyShift
    ld l,a
    ld h,0
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Дождаться клавиши через банковый ввод с курсором.
;
; вход:
;   hl = адрес состояния MXOS_KEY_STATE вызывающей программы.
;
; выход:
;   l = код клавиши, бит 0 в h обозначает событие, бит 1 — Ctrl. Допустим код клавиши
;   0.
;----------------------------------------------------------------------------

_mxos_bank_getch_cursor:
    call io_bankGetChCursor
    jp bankKeyResult

;----------------------------------------------------------------------------
; MXOS
;
; Дождаться клавиши в банковой программе.
;
; вход:
;   hl = адрес состояния MXOS_KEY_STATE вызывающей программы.
;
; выход:
;   l = код клавиши, бит 0 в h обозначает событие, бит 1 — Ctrl.
;----------------------------------------------------------------------------

_mxos_bank_getch:
    call io_bankGetCh
    jp bankKeyResult

;----------------------------------------------------------------------------
; MXOS
;
; Опросить банковую клавиатуру без ожидания.
;
; вход:
;   hl = адрес состояния MXOS_KEY_STATE вызывающей программы.
;
; выход:
;   hl = 0 при отсутствии события. Иначе l = код, h = 1 либо 3 для Ctrl. Нулевой код
;   клавиши также представим.
;----------------------------------------------------------------------------

_mxos_bank_key_poll:
    call io_bankKeyPoll

;----------------------------------------------------------------------------
; MXOS
;
; Упаковать флаги ввода IO.SYS в возвращаемое слово sccz80.
;
; вход:
;   z = 1 при отсутствии события. Иначе a = код клавиши, cf = признак Ctrl.
;
; выход:
;   hl = 0 при z = 1, иначе 0100h + a или 0300h + a при Ctrl. AF, BC и DE сохраняются.
;----------------------------------------------------------------------------

bankKeyResult:
    ld hl,0
    ret z
    ld l,a
    ld h,1
    ret nc
    ld h,3
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Дождаться символа через BIOS и вернуть его код.
;
; вход:
;   Параметров нет.
;
; выход:
;   hl = код клавиши из a, старший байт равен нулю.
;----------------------------------------------------------------------------

_mxos_getch:
    call mx_callRegs
    defw MXOS_BIOS_GETCH
    ld l,a
    ld h,0
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Получить код клавиши вместе с флагами GETCH.
;
; вход:
;   Параметров нет.
;
; выход:
;   h = код клавиши из a, l = флаги BIOS.
;----------------------------------------------------------------------------

_mxos_getkey:
    call mx_callRegs
    defw MXOS_BIOS_GETCH
    push af
    pop hl
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Опросить клавиатуру через BIOS и расширить результат до int.
;
; вход:
;   Параметров нет.
;
; выход:
;   hl = 0FFFFh для ответа 0FFh (клавиша отсутствует). Иначе hl = код клавиши с нулевым
;   старшим байтом.
;----------------------------------------------------------------------------

_mxos_keyscan:
    call mx_callRegs
    defw MXOS_BIOS_KEY_SCAN
    ld l,a
    ld h,0
    inc a
    ret nz
    dec h
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Очистить экран управляющим символом BIOS.
;
; вход:
;   Параметров нет.
;
; выход:
;   Код 31 передан PRINT_CHAR. Функция C возвращает void.
;----------------------------------------------------------------------------

_mxos_cls:
    ld c,31
    jp mx_printChar

;----------------------------------------------------------------------------
; MXOS
;
; Прочитать верхнюю границу памяти программ через прямой вход MEM.
;
; вход:
;   Параметров нет.
;
; выход:
;   hl = адрес последнего доступного байта.
;----------------------------------------------------------------------------

_mxos_memtop:
    jp mx_getMemTop

;----------------------------------------------------------------------------
; MXOS
;
; Установить верхнюю границу памяти через прямой вход MEM.
;
; вход:
;   hl = новый адрес последнего доступного байта.
;
; выход:
;   Новый предел доступен для последующего чтения. Функция C возвращает void.
;----------------------------------------------------------------------------

_mxos_set_memtop:
    jp mx_setMemTop

;----------------------------------------------------------------------------
; MXOS
;
; Прочитать координаты текстового курсора.
;
; вход:
;   Параметров нет.
;
; выход:
;   h = X/2, l = Y в системе координат BIOS.
;----------------------------------------------------------------------------

_mxos_cursor_get:
    jp mx_getCursorPos

;----------------------------------------------------------------------------
; MXOS
;
; Установить положение текстового курсора.
;
; вход:
;   h = X/2, l = Y в системе координат BIOS.
;
; выход:
;   BIOS принимает новое положение курсора. Функция C возвращает void.
;----------------------------------------------------------------------------

_mxos_cursor_set:
    jp mx_setCursorPos

;----------------------------------------------------------------------------
; MXOS
;
; Перевести код символа в верхний регистр через BIOS.
;
; вход:
;   l = исходный код символа.
;
; выход:
;   hl = обработанный код из a с нулевым старшим байтом.
;----------------------------------------------------------------------------

_mxos_upper:
    ld a,l
    call mx_callRegs
    defw MXOS_BIOS_UPPERCASE
    ld l,a
    ld h,0
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Вызвать ближнюю подпрограмму с регистрами из пакета MXOS_REGS.
;
; вход:
;   hl = адрес пяти доступных на запись слов: адрес входа, AF, BC, DE, HL. Код моста
;   допускает изменение операнда CALL. Вызов нереентерабелен.
;
; выход:
;   В тот же пакет записаны AF, BC, DE и HL подпрограммы, включая её флаги. Поле адреса
;   сохранено. Функция C возвращает void.
;----------------------------------------------------------------------------

_mxos_bios_call:
    push hl
    ld e,(hl)
    inc hl
    ld d,(hl)
    ex de,hl
    ld (bios_target+1),hl
    ex de,hl
    inc hl
    ld e,(hl)
    inc hl
    ld d,(hl)
    push de
    inc hl
    ld c,(hl)
    inc hl
    ld b,(hl)
    inc hl
    ld e,(hl)
    inc hl
    ld d,(hl)
    inc hl
    ld a,(hl)
    inc hl
    ld h,(hl)
    ld l,a
    pop af
bios_target:
    call 0
    push af
    push hl
    push de
    push bc
    ld hl,8
    add hl,sp
    ld e,(hl)
    inc hl
    ld d,(hl)
    ex de,hl
    ld bc,4
    add hl,bc
    pop de
    ld (hl),e
    inc hl
    ld (hl),d
    inc hl
    pop de
    ld (hl),e
    inc hl
    ld (hl),d
    inc hl
    pop de
    ld (hl),e
    inc hl
    ld (hl),d
    pop de
    pop hl
    inc hl
    inc hl
    ld (hl),e
    inc hl
    ld (hl),d
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Привязать к странице обработчик сброса очереди команд.
;
; вход:
;   hl = адрес обработчика в текущей странице либо 0 для отвязки.
;
; выход:
;   Управление возвращается через вход MEM. Последующие операции с очередью используют
;   установленную привязку.
;----------------------------------------------------------------------------

_mxos_queue_bind:
    jp mx_queueBind

;----------------------------------------------------------------------------
; MXOS
;
; Вызвать обработчик сброса очереди команд текущей страницы.
;
; вход:
;   Параметров нет. Привязка задаётся через _mxos_queue_bind.
;
; выход:
;   Обслужена привязанная очередь. Возвращаемого значения для C нет.
;----------------------------------------------------------------------------

_mxos_queue_flush:
    jp mx_queueFlush
