; Мост sccz80: единственный аргумент __z88dk_fastcall находится в HL.
; Возвращаем код DOS в HL, без зависимости от флагов в вызывающем C.
    SECTION code_clib
    INCLUDE "mxos_syscall_ids.inc"
    PUBLIC _mxos_file_call
    PUBLIC _mxos_current_drive

;----------------------------------------------------------------------------
; MXOS
;
; Выполнить файловую операцию над дескриптором sccz80.
;
; вход:
;   hl = адрес доступного для записи MXOS_FILE в странице вызывающего. Байт 63 задаёт
;   операцию FILEHANDLE.
;
; выход:
;   hl = возвращённый DOS байт a с нулевым старшим байтом. Дескриптор и
;   пользовательский буфер изменяются по правилам выбранной операции.
;----------------------------------------------------------------------------

_mxos_file_call:
    push hl
    ld de,63
    add hl,de
    ld a,(hl)
    pop hl
    call mx_callRegs
    defw MXOS_DOS_FILEHANDLE
    ld l,a
    ld h,0
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Узнать номер текущего диска DOS.
;
; вход:
;   Параметров нет.
;
; выход:
;   hl = номер диска из a, начиная с нуля для A:. Старший байт равен нулю.
;----------------------------------------------------------------------------

_mxos_current_drive:
    ld de,0
    call mx_callRegs
    defw MXOS_DOS_FILE_GET_SET_DRIVE
    ld l,a
    ld h,0
    ret
