SECTION code_crt_init
PUBLIC __Start
EXTERN _main
ORG 02000h

;----------------------------------------------------------------------------
; MXOS
;
; Запустить тест файлового SDK со стеком стенда и сохранить результат Си.
;
; вход:
;   Образ теста загружен по 2000h, область под стек до 8FDFh доступна для записи.
;   Регистровых аргументов нет.
;
; выход:
;   Слово из hl после _main записано по 5E80h. Управление передано стенду по 6100h без
;   возврата.
;----------------------------------------------------------------------------

__Start:
 ld sp,08FDFh
 call _main
 ld (05E80h),hl
 jp 06100h
