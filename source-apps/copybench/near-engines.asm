; Автономные near-кандидаты. Не включаются в BIOS.
; HL=источник, DE=назначение, BC=размер у byteCopy; диапазоны не пересекаются.
; Остальные входы: ровно 256 байт. AF/BC/DE/HL разрушены, SP сохранён.
    ORG 08000h

;----------------------------------------------------------------------------
; MXOS
;
; Скопировать неперекрывающиеся диапазоны для измерения побайтового движка.
;
; вход:
;   hl = источник, de = назначение, bc = длина в байтах; нулевой размер допустим.
;
; выход:
;   hl и de указывают сразу за диапазонами, bc = 0, a = 0, z = 1, cf = 0.
;----------------------------------------------------------------------------

byteCopy:
    ld a,b
    or c
    ret z
byteLoop:
    ld a,(hl)
    ld (de),a
    inc hl
    inc de
    dec bc
    ld a,b
    or c
    jp nz,byteLoop
    ret

; Только назначение выровнено; источник произвольный, с переносом в H.

;----------------------------------------------------------------------------
; MXOS
;
; Передать 256 байт с выровненным назначением.
;
; вход:
;   hl = произвольный источник, de = начало неперекрывающейся страницы назначения, e =
;   0.
;
; выход:
;   hl продвинут на 256 байт. de снова указывает на начало страницы; bc сохранён, a =
;   последний байт, z = 1.
;----------------------------------------------------------------------------

alignedByte256:
alignedByteLoop:
    DUP 8
    ld a,(hl)
    ld (de),a
    inc hl
    inc e
    EDUP
    jp nz,alignedByteLoop
    ret

;----------------------------------------------------------------------------
; MXOS
;
; Скопировать 256 байт, читая источник командами POP.
;
; вход:
;   hl = источник, de = неперекрывающееся назначение. Стек и код доступны для временной
;   смены SP и записи операндов. Прерывания выключены.
;
; выход:
;   В назначение записано 256 байт. SP восстановлен; hl = адрес за назначением, b = 0,
;   z = 1. de содержит последнее прочитанное слово.
;----------------------------------------------------------------------------

stack256:
    ld (stackReadSP+1),hl
    ld hl,0
    add hl,sp
    ld (stackRestoreSP+1),hl
    ex de,hl
    ld b,16
stackReadSP:
    ld sp,0
stackLoop:
    DUP 8
    pop de
    ld (hl),e
    inc hl
    ld (hl),d
    inc hl
    EDUP
    dec b
    jp nz,stackLoop
stackRestoreSP:
    ld sp,0
    ret

; Назначение выровнено. INC L стоит столько же, сколько INX H,
; но даёт Z для окончания сектора и освобождает отдельный счётчик B.

;----------------------------------------------------------------------------
; MXOS
;
; Скопировать 256 байт через стек в выровненную страницу.
;
; вход:
;   hl = источник, de = назначение с e = 0. Диапазоны не перекрываются, прерывания
;   выключены, операнды SP доступны для записи.
;
; выход:
;   Страница заполнена, hl указывает на её начало, SP восстановлен. de = последнее
;   слово источника, bc сохранён, z = 1.
;----------------------------------------------------------------------------

alignedStack256:
    ld (alignedReadSP+1),hl
    ld hl,0
    add hl,sp
    ld (alignedRestoreSP+1),hl
    ex de,hl
alignedReadSP:
    ld sp,0
alignedStackLoop:
    DUP 8
    pop de
    ld (hl),e
    inc l
    ld (hl),d
    inc l
    EDUP
    jp nz,alignedStackLoop
alignedRestoreSP:
    ld sp,0
    ret
    END
