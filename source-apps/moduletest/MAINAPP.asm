; Нативная main-программа: затирает нижний RUN, завершает работу через RET.
    INCLUDE "../../sdk/asm/mxos.inc"
IMAGE_FLAGS = IMAGE_FLAG_MAIN
    ORG 0000h

;----------------------------------------------------------------------------
; MXOS
;
; Проверить запуск приложения MAIN и возврат в загрузчик.
;
; вход:
;   Выбран профиль MAIN, слово по 8800h доступно для записи. Параметры в регистрах не
;   используются.
;
; выход:
;   Сообщение выведено через BIOS, в 8800h записано 55AAh, hl = 55AAh. Управление
;   возвращается через RET.
;----------------------------------------------------------------------------

entry:
    ld hl,message
    call bios_printString
    ld hl,055AAh
    ld (08800h),hl
    ret
message: DB 'Native main application',13,10,0
